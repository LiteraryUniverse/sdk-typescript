import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { plugin as operations } from '@graphql-codegen/typescript-operations'
import { buildSchema, Kind, parse, print, validate } from 'graphql'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const document = parse(
	readFileSync(resolve(root, 'src/operations.graphql'), 'utf8'),
)
const schema = buildSchema(
	readFileSync(resolve(root, 'schema.graphql'), 'utf8'),
)
const errors = validate(schema, document)
if (errors.length)
	throw new Error(errors.map((error) => error.message).join('\n'))

const documents = [{ document, location: 'operations.graphql' }]
const config = {
	enumsAsTypes: true,
	onlyOperationTypes: true,
	preResolveTypes: true,
	useTypeImports: true,
	avoidOptionals: { field: true },
	defaultScalarType: 'unknown',
	scalars: {
		DateTime: 'string',
		Locale: 'string',
		URL: 'string',
		JSON: './json.js#JsonValue',
	},
}
const outputs = [await operations(schema, documents, config)]
const declarations = [
	...new Set(
		outputs.flatMap((output) =>
			typeof output === 'string' ? [] : (output.prepend ?? []),
		),
	),
]
const contents = outputs.map((output) =>
	typeof output === 'string' ? output : output.content,
)
const queries = document.definitions.map((definition) => {
	if (
		definition.kind !== Kind.OPERATION_DEFINITION ||
		!definition.name ||
		!['query', 'mutation'].includes(definition.operation)
	)
		throw new Error('SDK documents must be named query or mutation operations')
	return `export const ${definition.name.value}Document = ${JSON.stringify(print(definition))} as const`
})
const generated = [
	'// Generated by npm run generate. Do not edit.',
	...declarations,
	...contents,
	...queries,
	'',
].join('\n')
const target = resolve(root, 'src/generated.ts')
if (process.argv.includes('--check')) {
	if (readFileSync(target, 'utf8') !== generated)
		throw new Error('SDK artifacts are stale; run npm run generate')
} else writeFileSync(target, generated)
console.log(
	`Validated and generated ${queries.length} standalone SDK operations`,
)

const imagePolicy = JSON.parse(
	readFileSync(resolve(root, 'image-policy.json'), 'utf8'),
)
const imageTypes = `// Generated by npm run generate. Do not edit.
export const IMAGE_POLICY = ${JSON.stringify(imagePolicy, null, 2)} as const
export type ImagePurpose = keyof typeof IMAGE_POLICY.purposes
export type ImagePolicy = {
  version: string; maxSourceBytes: number; maxDecodedPixels: number;
  maxUploadPixels: number; processingSeconds: number;
  purposes: Record<ImagePurpose, { maxBytes: number; allowedTypes: readonly string[];
    maxWidth: number; maxHeight: number; aspectRatio: number | null;
    recommendedWidth: number | null; recommendedHeight: number | null }>
}
`
const imageTarget = resolve(root, 'src/imagePolicy.ts')
if (process.argv.includes('--check')) {
	if (readFileSync(imageTarget, 'utf8') !== imageTypes)
		throw new Error('SDK image policy is stale; run npm run generate')
} else writeFileSync(imageTarget, imageTypes)
